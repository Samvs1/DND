"""Label sheets for the M36.8b labellers (artifacts only, gitignored).

Each sheet row is a selected candidate plus what a labeller needs to pick the expected choice: the
menu exactly as the chooser sees it (`prompt`: the CHOOSE prompt's ACTING HERO, TARGETS, PRONOUNS,
RECENT ENGINE EVENTS and MENU sections, from the one context builder; a full entry list would be
four times larger, mostly give/hand/drop rows the MENU section's ITEMS line already spells out),
the exact fast-path pick if the line is a game string, and a weak hint (what the engine
did).

Public API: `sheet_rows(rows)`, `split(rows, parts)`, `write_sheets(rows, out_dir)`, `README`.
"""

import hashlib
import json
import os
from collections import defaultdict
from pathlib import Path
from typing import Any

from aidm.dm.chooser import exact_choice
from aidm.dm.context import ContextPurpose, SectionKey, build_context
from aidm.models.action_menu import ActionMenu, MenuChoice
from aidm.models.events import AnyEvent
from aidm.models.state import GameState
from scripts.interpret import lib

PARTS = 3
README = """M36.8b label sheets (generated by scripts/select_label_rows.py --sheets; do not edit).

Read docs/next/M36_LABELLING.md first, then the worked examples in
artifacts/interpret/labels/examples.jsonl (the first 15 rows of part1, already labelled).

Your sheet: artifacts/interpret/sheets/partN.jsonl (N = 1, 2 or 3). For EVERY row of it write
exactly one corpus row, in the same order, to artifacts/interpret/labels/partN.jsonl (one JSON
object per line, ASCII only):

{"id": <copy>, "run": <copy>, "seq": <copy>, "actor_id": <copy>, "text": <copy>,
 "scope": <copy>, "expect": {"steps": [{"entry": "<menu id>", "targets": ["<target id>"],
 "qty": 1}], "other": false, "other_first": false}, "alt": [], "source": <copy>, "note": "<short>"}

- entry ids and target ids come ONLY from the row's `prompt` (MENU and TARGETS, exactly what the
  model sees; a group line give:<item> -> ...: <item> = any of ITEMS stands for one id per item,
  e.g. give:block-of-incense).
- qty is 1 unless the entry says "up to N" and the player asked for more.
- other = true when the line (or part of it) is a stunt or something no entry does; other_first =
  true only when that part comes before the steps. A pure flourish is NOT other.
- alt only for a genuinely equal second reading (same shape as expect).
- keep source as given; part1 rows 1-15 are already done in examples.jsonl: copy them.
- hint_engine is a weak hint (often wrong); label what the player asked for.
- If no menu entry can express what the player clearly asked for, still write your best row and
  put "MENU GAP: <what is missing>" in note.

Check your file: python scripts/eval_interpret.py --corpus artifacts/interpret/labels/partN.jsonl
(offline; every gap it lists must be a typo you fix or a MENU GAP note).
"""


def _prompt(state: GameState, line: lib.Line, menu: ActionMenu, recent: list[AnyEvent]) -> str:
    actor = line.event.creature_id
    pack = build_context(
        state, ContextPurpose.CHOOSE, actor, line.event.text, events=recent, menu=menu
    )
    return "\n\n".join(s.text() for s in pack.sections if s.key is not SectionKey.SYSTEM)


def _choice(choice: MenuChoice | None) -> dict[str, Any] | None:
    if choice is None:
        return None
    steps = [{"entry": s.entry, "targets": list(s.targets), "qty": s.qty} for s in choice.steps]
    return {"steps": steps, "other": choice.other, "other_first": choice.other_first}


def _sheet_row(row: dict[str, Any], line: lib.Line) -> dict[str, Any]:
    menu = lib.menu_for(line.state, line.event.creature_id)
    keep = ("id", "run", "seq", "actor_id", "text", "scope", "source", "note")
    return {
        **{k: row[k] for k in keep},
        "exact": _choice(exact_choice(menu, line.event.text)),
        "hint_engine": row.get("engine", []),
        "prompt": _prompt(line.state, line, menu, line.recent),
    }


def sheet_rows(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """The rows with their rendered menus, in the order given (one walk per run)."""
    by_run: dict[str, dict[int, dict[str, Any]]] = defaultdict(dict)
    for row in rows:
        by_run[row["run"]][int(row["seq"])] = row
    built: dict[str, dict[str, Any]] = {}
    for run, wanted in sorted(by_run.items()):
        for line in lib.walk(run, frozenset(wanted)):
            built[line.id] = _sheet_row(wanted[line.seq], line)
    return [built[r["id"]] for r in rows]


def _mix_key(row_id: str) -> str:
    return hashlib.sha1(row_id.encode("utf-8")).hexdigest()


def split(rows: list[dict[str, Any]], parts: int = PARTS) -> list[list[dict[str, Any]]]:
    """Deal each scope's rows round-robin over the parts (sizes differ by at most one, every
    scope spread evenly); inside a part the order is a fixed mix by id hash."""
    out: list[list[dict[str, Any]]] = [[] for _ in range(parts)]
    turn = 0
    for scope in sorted({str(r["scope"]) for r in rows}):
        for row in sorted((r for r in rows if str(r["scope"]) == scope), key=lambda r: r["id"]):
            out[turn % parts].append(row)
            turn += 1
    return [sorted(part, key=lambda r: _mix_key(r["id"])) for part in out]


def _write_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    tmp = path.with_suffix(".tmp")
    with tmp.open("w", encoding="utf-8", newline="\n") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=True) + "\n")
    os.replace(tmp, path)


def write_sheets(rows: list[dict[str, Any]], out_dir: Path) -> list[tuple[Path, int]]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[tuple[Path, int]] = []
    for index, part in enumerate(split(sheet_rows(rows)), start=1):
        path = out_dir / f"part{index}.jsonl"
        _write_jsonl(path, part)
        written.append((path, len(part)))
    (out_dir / "README.txt").write_text(README, encoding="utf-8", newline="\n")
    return written
