"""Write ASSETS_TODO.md: every manifest entry that is still a placeholder (Addendum A.4).

For each entry: key, the exact target file path, size, transparency need and the ready-to-use prompt
(style bible prefix + subject details from the data, see aidm/server/asset_prompts.py). A later
generator (scripts/gen_assets.py, Addendum B) reads the same manifest; a human can also just drop
the file at the listed path and run `python scripts/build_manifest.py`.

Usage: python scripts/gen_assets_todo.py [--check]   (--check exits 1 when ASSETS_TODO.md is stale)
"""

from __future__ import annotations

import io
import json
import sys
from pathlib import Path
from typing import Any

KIND_ORDER = (
    "portrait",
    "monster_token",
    "item_icon",
    "spell_icon",
    "condition_icon",
    "zone_card",
    "region_banner",
    "music",
    "sfx",
)
STATIC = "aidm/web/static"
HEADER = [
    "# ASSETS_TODO",
    "",
    "<!-- GENERATED by scripts/gen_assets_todo.py from the manifest. Do not edit by hand. -->",
    "",
    "Every asset below is still a generated placeholder. To replace one: save the image (or audio",
    "file) at the exact `file` path, then run `python scripts/build_manifest.py` and",
    "`python scripts/gen_assets_todo.py`. Prompts start with the style bible",
    "(`docs/STYLE_BIBLE.md`). Never overwrite a real or v1 asset.",
    "",
]


def repo_root() -> Path:
    return Path(__file__).resolve().parent.parent


def manifest_file(root: Path) -> Path:
    return root / "aidm" / "web" / "static" / "assets" / "manifest.json"


def todo_file(root: Path) -> Path:
    return root / "ASSETS_TODO.md"


def load_manifest(root: Path) -> dict[str, dict[str, Any]]:
    raw = json.loads(manifest_file(root).read_text(encoding="utf-8"))
    return raw if isinstance(raw, dict) else {}


def _rank(entry: dict[str, Any], key: str) -> tuple[int, str]:
    kind = str(entry["kind"])
    return (KIND_ORDER.index(kind) if kind in KIND_ORDER else len(KIND_ORDER), key)


def _size(entry: dict[str, Any]) -> str:
    size = entry.get("size")
    return f"{size[0]}x{size[1]}" if size else "n/a (audio)"


def render(manifest: dict[str, dict[str, Any]]) -> str:
    todo = {k: v for k, v in manifest.items() if v.get("status") == "placeholder"}
    ordered = sorted(todo.items(), key=lambda item: _rank(item[1], item[0]))
    lines = list(HEADER)
    counts = {kind: sum(1 for v in todo.values() if v["kind"] == kind) for kind in KIND_ORDER}
    lines.append(
        f"{len(todo)} placeholder entries: " + ", ".join(f"{k} {n}" for k, n in counts.items() if n)
    )
    kind = ""
    for key, entry in ordered:
        if entry["kind"] != kind:
            kind = str(entry["kind"])
            lines += ["", f"## {kind} ({counts.get(kind, 0)})"]
        lines += [
            "",
            f"### {key}",
            f"- file: {STATIC}/{entry['file']}",
            f"- size: {_size(entry)}",
            f"- transparent: {'yes' if entry.get('transparent') else 'no'}",
            f"- prompt: {entry.get('prompt') or '(missing)'}",
        ]
    return "\n".join(lines) + "\n"


def run(root: Path, *, check: bool) -> int:
    text = render(load_manifest(root))
    path = todo_file(root)
    if check:
        current = path.read_text(encoding="utf-8") if path.is_file() else ""
        if current == text:
            print("assets todo: ok")
            return 0
        print("assets todo: STALE, run python scripts/gen_assets_todo.py")
        return 1
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"assets todo: wrote {path.name} ({text.count(chr(10) + '### ')} entries)")
    return 0


def main(argv: list[str]) -> int:
    if isinstance(sys.stdout, io.TextIOWrapper):
        sys.stdout.reconfigure(encoding="utf-8")
    return run(repo_root(), check="--check" in argv)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
