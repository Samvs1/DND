"""Generate aidm/web/protocol.json and docs/PROTOCOL.md from aidm.models.protocol.

Usage: python scripts/gen_protocol.py [--check]
"""

from __future__ import annotations

import io
import json
import sys
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from aidm.models import protocol

HEADER = "<!-- GENERATED by scripts/gen_protocol.py. Do not edit by hand. -->"


def repo_root() -> Path:
    return Path(__file__).resolve().parent.parent


def message_type_name(model: type[BaseModel]) -> str:
    return str(model.model_json_schema()["properties"]["type"]["const"])


def build_json() -> str:
    data: dict[str, Any] = {
        "client": {
            "schema": protocol.client_adapter.json_schema(),
            "types": sorted(message_type_name(m) for m in protocol.CLIENT_MESSAGES),
        },
        "server": {
            "schema": protocol.server_adapter.json_schema(),
            "types": sorted(message_type_name(m) for m in protocol.SERVER_MESSAGES),
        },
    }
    return json.dumps(data, indent=2, sort_keys=True) + "\n"


def _field_cell(name: str, prop: dict[str, Any], required: bool) -> str:
    kind = prop.get("const", prop.get("type", "any"))
    label = f"`{name}`: {kind}"
    return label if required else label + " (optional)"


def _row(direction: str, model: type[BaseModel]) -> str:
    schema = model.model_json_schema()
    required = set(schema.get("required", []))
    props: dict[str, dict[str, Any]] = schema.get("properties", {})
    fields = [_field_cell(n, props[n], n in required) for n in sorted(props)]
    return f"| {direction} | `{message_type_name(model)}` | {', '.join(fields)} |"


def build_markdown() -> str:
    lines = [
        HEADER,
        "",
        "# Protocol",
        "",
        "Websocket messages. Source: `aidm/models/protocol.py`.",
        "Machine-readable schema: `aidm/web/protocol.json`.",
        "",
        "| Direction | Type | Fields |",
        "|---|---|---|",
    ]
    rows = [("client", m) for m in protocol.CLIENT_MESSAGES]
    rows += [("server", m) for m in protocol.SERVER_MESSAGES]
    rows.sort(key=lambda r: (r[0], message_type_name(r[1])))
    lines.extend(_row(d, m) for d, m in rows)
    return "\n".join(lines) + "\n"


def targets(root: Path) -> dict[Path, str]:
    return {
        root / "aidm" / "web" / "protocol.json": build_json(),
        root / "docs" / "PROTOCOL.md": build_markdown(),
    }


def write_all(root: Path) -> None:
    for path, content in targets(root).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(root).as_posix()}")


def stale_files(root: Path) -> list[str]:
    stale: list[str] = []
    for path, content in targets(root).items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != content:
            stale.append(path.relative_to(root).as_posix())
    return stale


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    root = repo_root()
    if "--check" in args:
        stale = stale_files(root)
        for rel in stale:
            print(f"out of date: {rel}")
        if stale:
            print("protocol: out of date, run python scripts/gen_protocol.py")
            return 1
        print("protocol: ok")
        return 0
    write_all(root)
    return 0


if __name__ == "__main__":
    if isinstance(sys.stdout, io.TextIOWrapper):
        sys.stdout.reconfigure(encoding="utf-8")
    raise SystemExit(main())
