"""Render ASSETS_REPORT.md (Addendum B.5 step 6): spend, verdicts, counts. Deterministic, ASCII.

Public API: `render_report`, `write_report`, `CAP_EUR`, `LICENSE`.
"""

import json
import os
import re
from collections import Counter
from pathlib import Path
from typing import Any

from aidm.server.assetgen.ledger import load_ledger

CAP_EUR = 8.00
LICENSE = "AI generated via OpenAI API, check provider terms before commercial use"
SCORES = ("subject", "style", "composition", "cleanliness", "readability_64")
_REVIEW = re.compile(r"^review_(\d+)\.json$")


def _reviews(art: Path) -> dict[str, dict[str, Any]]:
    """Latest verdict per key (highest review number wins)."""
    files = sorted(
        (int(m.group(1)), p) for p in art.glob("review_*.json") if (m := _REVIEW.match(p.name))
    )
    latest: dict[str, dict[str, Any]] = {}
    for _, path in files:
        latest.update(json.loads(path.read_text(encoding="utf-8")))
    return latest


def _attempts(art: Path) -> Counter[str]:
    counts: Counter[str] = Counter()
    for sidecar in sorted((art / "candidates").glob("*.json")):
        counts.update(set(json.loads(sidecar.read_text(encoding="utf-8")).get("keys", [])))
    return counts


def _spend(ledger_path: Path) -> list[str]:
    ledger = load_ledger(ledger_path)
    spent = ledger.committed_eur()
    models = sorted({e.model for e in ledger.entries})
    return [
        "## Spend",
        "",
        f"- Committed: {spent:.4f} EUR over {len(ledger.entries)} calls",
        f"- Cap: {CAP_EUR:.2f} EUR",
        f"- Remaining: {CAP_EUR - spent:.4f} EUR",
        f"- Model id(s): {', '.join(models) if models else 'none'}",
        "",
    ]


def _verdicts(art: Path, manifest: dict[str, Any]) -> tuple[list[str], list[str]]:
    reviews, attempts = _reviews(art), _attempts(art)
    rows = [
        "## Verdicts",
        "",
        "| key | attempts | " + " | ".join(SCORES) + " | verdict | installed |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    rejected: list[str] = []
    for key in sorted(reviews):
        r = reviews[key]
        installed = str(manifest.get(key, {}).get("source", "")).startswith("generated:")
        scores = " | ".join(str(r.get(s, "-")) for s in SCORES)
        verdict = str(r.get("verdict", "-"))
        shown = "yes" if installed else "no"
        rows.append(f"| {key} | {attempts.get(key, 0)} | {scores} | {verdict} | {shown} |")
        if not installed:
            rejected.append(f"- {key}: last verdict {verdict}, {attempts.get(key, 0)} attempts")
    return rows + [""], rejected


def _counts(manifest: dict[str, Any]) -> tuple[list[str], Counter[str]]:
    gen: Counter[str] = Counter()
    left: Counter[str] = Counter()
    for entry in manifest.values():
        if str(entry.get("source", "")).startswith("generated:"):
            gen[entry["kind"]] += 1
        elif entry.get("status") == "placeholder":
            left[entry["kind"]] += 1
    lines = ["## Counts", "", f"- Generated: {sum(gen.values())}"]
    lines += [f"  - {k}: {gen[k]}" for k in sorted(gen)]
    lines += [f"- Placeholders left: {sum(left.values())}"]
    lines += [f"  - {k}: {left[k]}" for k in sorted(left)]
    return lines + [""], left


def render_report(manifest_path: Path, art: Path, ledger_path: Path) -> str:
    manifest: dict[str, Any] = json.loads(manifest_path.read_text(encoding="utf-8"))
    verdicts, rejected = _verdicts(art, manifest)
    counts, left = _counts(manifest)
    lines = ["# Assets report", "", "Generated by scripts/assets_report.py.", ""]
    lines += _spend(ledger_path) + verdicts + counts
    lines += ["## Rejected or exhausted (left as placeholders)", ""]
    lines += (rejected or ["- none"]) + ["", "## Not generated (P2 and uncovered)", ""]
    lines += [f"- {k}: {left[k]} placeholders remain" for k in sorted(left)]
    lines += [
        "- Known P1 gaps (docs/DECISIONS.md M10.1): the manifest has no surface art keys, so no "
        "surface icons exist; only the damage, item and spell icons the manifest has keys for "
        "were generated.",
        "",
        "## License and revert",
        "",
        f"- License: {LICENSE}",
        "- Any generated asset can be reverted with `python scripts/revert_asset.py <key>`.",
        "",
    ]
    return "\n".join(lines)


def write_report(manifest_path: Path, art: Path, ledger_path: Path, out: Path) -> Path:
    tmp = out.with_name(out.name + ".tmp")
    tmp.write_text(render_report(manifest_path, art, ledger_path), encoding="utf-8", newline="\n")
    os.replace(tmp, out)
    return out
