"""P1/P2 asset priority derived from the manifest and the data registries (Addendum B.1).

Eligible: an image entry (not music/sfx) that is a placeholder or was generated by this pipeline;
never `source: v1` or hand-made real art. P1 rules, in order:
- wizard portraits: every race and class portrait choice (one per race and sex: one look each);
- NPC archetypes: the humanoid stat blocks (CR <= the campaign generator's cap) it can pick, one
  image per stat-block family (the name before the comma, e.g. the three forms of one
  lycanthrope): the "Human Form" member when there is one, else the first id;
- monsters: the 30 most frequently encounterable tokens, ranked by the number of terrain tables
  that list them (encounter_monsters tags), then lower tier (CR band) first, then CR, then id;
- one icon per item category and per damage type (damage types use `spell_icon.school.<type>`);
- surface icons: the first 5 surfaces (data order) that have a `surface_icon` key;
- region banners: the tier banners first, then terrains by how many encounter monsters they
  host, 6 in all.
Every other eligible entry is P2. Output is deterministic (no clock, sorted).

Public API: `PriorityTiers`, `derive_tiers`, `render_priority`, `is_eligible`.
"""

from collections.abc import Mapping
from dataclasses import dataclass
from typing import Any

from aidm.data.encounter_monsters import encounter_monsters
from aidm.data.item_catalogue import ItemCategory
from aidm.data.srd import srd
from aidm.data.surface_defs import surface_defs
from aidm.server.asset_keys import AUDIO_KINDS, MAX_ARCHETYPE_CR, split_key

type Manifest = Mapping[str, Mapping[str, Any]]

P1_MONSTERS = 30
P1_BANNERS = 6
P1_SURFACES = 5
PREFERRED_FORM = "human form"
HAND_SOURCES = frozenset({"v1", "manual"})


@dataclass(frozen=True)
class PriorityTiers:
    p1: dict[str, str]
    p2: tuple[str, ...]
    notes: tuple[str, ...]


def is_eligible(entry: Mapping[str, Any]) -> bool:
    source = str(entry.get("source") or "")
    if entry.get("kind") in AUDIO_KINDS or source in HAND_SOURCES:
        return False
    return entry.get("status") == "placeholder" or source.startswith("generated:")


def _wizard(manifest: Manifest) -> tuple[list[str], list[str]]:
    prefixes = ("portrait.race.", "portrait.class.")
    return sorted(k for k in manifest if k.startswith(prefixes)), []


def _npcs(manifest: Manifest) -> tuple[list[str], list[str]]:
    families: dict[str, list[tuple[str, str]]] = {}
    for m in srd().monsters.all():
        key = f"portrait.npc.{m.index}"
        if m.type == "humanoid" and m.challenge_rating <= MAX_ARCHETYPE_CR and key in manifest:
            families.setdefault(m.name.split(",")[0].strip().lower(), []).append((m.index, m.name))
    picked: list[str] = []
    notes: list[str] = []
    for family in sorted(families):
        members = sorted(families[family])
        best = next((i for i, n in members if PREFERRED_FORM in n.lower()), members[0][0])
        picked.append(f"portrait.npc.{best}")
        others = [i for i, _ in members if i != best]
        if others:
            notes.append(
                f"NPC look `{family}`: {best} (P1); {', '.join(others)} share its look (P2)"
            )
    return picked, notes


def _monsters(manifest: Manifest) -> tuple[list[str], list[str]]:
    ranked = sorted(encounter_monsters().all(), key=lambda m: (-len(m.tags), m.tier, m.cr, m.index))
    keys = [f"monster_token.{m.index}" for m in ranked]
    return [k for k in keys if k in manifest][:P1_MONSTERS], []


def _icons(manifest: Manifest) -> tuple[list[str], list[str]]:
    picked = [f"item_icon.{c.value}" for c in ItemCategory if f"item_icon.{c.value}" in manifest]
    missing: list[str] = []
    for damage in srd().damage_types.all():
        key = f"spell_icon.school.{damage.index}"
        if key in manifest:
            picked.append(key)
        else:
            missing.append(damage.index)
    notes = (
        [f"damage types with no art key (shown as text): {', '.join(missing)}"] if missing else []
    )
    return picked, notes


def _surfaces(manifest: Manifest) -> tuple[list[str], list[str]]:
    keys = [f"surface_icon.{s.index}" for s in surface_defs().all()]
    picked = [k for k in keys if k in manifest][:P1_SURFACES]
    if picked:
        return picked, []
    return [], ["surface icons: the manifest has no `surface_icon` key (surfaces are text chips)"]


def _banners(manifest: Manifest) -> tuple[list[str], list[str]]:
    hosted: dict[str, int] = {}
    for m in encounter_monsters().all():
        for tag in m.tags:
            hosted[tag] = hosted.get(tag, 0) + 1

    def rank(key: str) -> tuple[int, int, str]:
        slug = split_key(key)[1]
        return (0 if slug.startswith("tier") else 1, -hosted.get(slug, 0), slug)

    banners = sorted((k for k in manifest if k.startswith("region_banner.")), key=rank)
    return banners[:P1_BANNERS], []


RULES = (
    ("wizard portrait", _wizard),
    ("NPC archetype portrait", _npcs),
    ("frequent monster", _monsters),
    ("category / damage icon", _icons),
    ("surface icon", _surfaces),
    ("region banner", _banners),
)


def derive_tiers(manifest: Manifest) -> PriorityTiers:
    """P1 (rule label per key, rule order) and P2 (sorted) over the eligible entries."""
    eligible = {k for k, e in manifest.items() if is_eligible(e)}
    p1: dict[str, str] = {}
    notes: list[str] = []
    for label, rule in RULES:
        keys, rule_notes = rule(manifest)
        notes += rule_notes
        for key in keys:
            if key in eligible and key not in p1:
                p1[key] = label
    p2 = tuple(sorted(eligible - set(p1)))
    return PriorityTiers(p1=p1, p2=p2, notes=tuple(notes))


def _counts(keys: list[str]) -> str:
    kinds: dict[str, int] = {}
    for key in keys:
        kinds[split_key(key)[0]] = kinds.get(split_key(key)[0], 0) + 1
    return ", ".join(f"{k} {n}" for k, n in sorted(kinds.items()))


def render_priority(tiers: PriorityTiers) -> str:
    """docs/ASSET_PRIORITY.md text."""
    lines = [
        "# ASSET_PRIORITY",
        "",
        "<!-- GENERATED by scripts/gen_assets.py --write-priority. Do not edit by hand. -->",
        "",
        "Tiers for AI asset generation (docs/ADDENDUM_ASSET_GEN.md B.1), derived from the manifest",
        "and the data registries by `aidm/server/assetgen/priority.py`. Only placeholder entries",
        "are ever generated; real and v1 art is never selected and existing files are never",
        "overwritten. P2 is generated only with `--tier 2`.",
        "",
        f"P1: {len(tiers.p1)} entries ({_counts(list(tiers.p1))}).",
        f"P2: {len(tiers.p2)} entries ({_counts(list(tiers.p2))}).",
        "",
        "## P1",
    ]
    for label, _ in RULES:
        keys = [k for k, rule in tiers.p1.items() if rule == label]
        lines += ["", f"### {label} ({len(keys)})", ""]
        lines += [f"- {k}" for k in keys] or ["- (none)"]
    lines += ["", "## Notes", ""]
    lines += [f"- {n}" for n in tiers.notes] or ["- (none)"]
    lines += ["", "## P2", ""]
    by_kind: dict[str, list[str]] = {}
    for key in tiers.p2:
        by_kind.setdefault(split_key(key)[0], []).append(split_key(key)[1])
    lines += [f"- {kind} ({len(s)}): {', '.join(s)}" for kind, s in sorted(by_kind.items())]
    return "\n".join(lines) + "\n"
